#!/bin/bash
# Generate the compact routing index for triangulate recurring rules.
# common-rules.md remains the sole source of truth.

set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE="${1:-$SCRIPT_DIR/../skills/triangulate/common-rules.md}"
OUTPUT="${2:-$SCRIPT_DIR/../skills/triangulate/common-rules.digest.md}"
MODE="${3:-write}"
AWK_LIB="$SCRIPT_DIR/lib/md-rule-rows.awk"
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

[ -f "$SOURCE" ] || { echo "Error: missing $SOURCE" >&2; exit 2; }
# Fail closed rather than emitting a digest with no rows: a missing library
# would otherwise produce an empty table that the row-count guard below catches
# only by accident, with a message about the source file rather than the tool.
[ -f "$AWK_LIB" ] || { echo "Error: missing $AWK_LIB" >&2; exit 2; }

{
  echo '<!-- Generated by hooks/generate-triangulate-rule-digest.sh; do not edit. -->'
  echo '# Triangulate Recurring Rule Digest'
  echo
  echo 'Read this routing index first. Match the diff against pattern names, then extract only the triggered rows from `common-rules.md` with:'
  echo
  echo '```bash'
  echo "rg -n '^\\| (R1|R3|RS2|RT4) \\|' skills/triangulate/common-rules.md"
  echo '```'
  echo "If \`rg\` is unavailable, use the environment's Grep/search tool with the same anchored pattern."
  echo
  # Both Floors are sections, not rows, so anchored row extraction never
  # surfaces them. Without these pointers they are unreachable in deployment:
  # a 4-run probe showed zero reads of the Remedy Floor as merged, and the
  # round-7 ablation showed reviewers carrying its pointer produce the floor's
  # remedy properties while reviewers without it do not (evals/rule-ablation).
  # Round 12 measured the Finding Floor the same way: wired, the Critical/Major
  # findings that turn out not to be defects fall from 4.12 per review to 1.62
  # while genuine defects reached stays flat (16.88 -> 16.50).
  echo 'Every finding you write must also satisfy the **Finding Floor** — three clauses every finding inherits. Extract that section once per review:'
  echo
  echo '```bash'
  echo "awk '/^### Finding Floor/,/^### Remedy Floor/' skills/triangulate/common-rules.md"
  echo '```'
  echo
  echo 'Every `Fix:` you write must also satisfy the **Remedy Floor** — five clauses every rule'"'"'s remedy inherits. Extract that section once per review:'
  echo
  echo '```bash'
  echo "awk '/^### Remedy Floor/,/^### Anti-Deferral/' skills/triangulate/common-rules.md"
  echo '```'
  echo
  echo "Also extract a rule's Extended obligations section when the selected row points to it. Do not read the full rules file unless targeted extraction is inconclusive."
  echo
  echo '| ID | Pattern | Severity if missed |'
  echo '|---|---|---|'
  # Row parsing lives in lib/md-rule-rows.awk, shared with check-rule-sync.sh.
  # It must be shared: when the two had separate copies, only one learned that a
  # backslash-escaped pipe is part of a cell rather than a delimiter, so a
  # severity of `Critical \| Major` lost its escalation here while the linter
  # compared the digest against this same wrong output and reported agreement.
  awk -v want=rows -f "$AWK_LIB" "$SOURCE"
  # Truncation terminator. The digest is read WHOLE as the routing index
  # (SKILL.md), and its tail is the RS*/RT* rows — a read cut short deletes the
  # security and testing checklists while still looking complete. Must be the
  # LAST line: a terminator emitted mid-file is one a truncated read can see,
  # which is the failure mode it exists to reveal.
  echo '## END-OF-DIGEST'
} > "$TMP"

[ "$(grep -Ec '^\| (R[0-9]+|RS[0-9]+|RT[0-9]+) \|' "$TMP")" -gt 0 ] || {
  echo 'Error: no recurring-rule rows found' >&2
  exit 2
}

if [ "$MODE" = "--check" ]; then
  if ! cmp -s "$TMP" "$OUTPUT"; then
    echo "Triangulate rule digest is stale. Run: bash hooks/generate-triangulate-rule-digest.sh" >&2
    exit 1
  fi
  echo 'Triangulate rule digest is up to date.'
elif [ "$MODE" = "write" ]; then
  cp "$TMP" "$OUTPUT"
else
  echo "Usage: $0 [source] [output] [write|--check]" >&2
  exit 2
fi
